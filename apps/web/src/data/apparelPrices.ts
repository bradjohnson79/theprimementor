const NON_APPAREL = /sticker|magnet|button|phone|mug|bottle|pillow|tote|\bbag\b|cap|hat|beanie|bandana|apron|\bbib\b|poster|mouse|sock|mask|patch|\bpin\b|canvas|blanket|towel|ornament|coaster|journal|notebook|keychain|clock|puzzle|\bcase\b|drawstring/i;
const APPAREL = /t-shirt|\btee\b|hoodie|sweatshirt|tank|bodysuit|polo|long sleeve|ringer|sleeveless shirt/i;

export function isApparelProductName(name: string): boolean {
  return APPAREL.test(name) && !NON_APPAREL.test(name);
}

/** Cheapest garment. Accessories never qualify, even if they are the lowest SKU. */
export function lowestApparelPrice(offers: ApparelPriceOffer[]): number | null {
  const amounts = offers.filter((offer) => isApparelProductName(offer.name)).map((offer) => offer.amountCAD);
  if (amounts.length === 0) return null;
  return Math.min(...amounts);
}

